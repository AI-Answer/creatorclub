// Writes shared/motion/icons.ts: the icons a motion graphic can show, as inline SVG, so the preview and the export draw them with no
// network and no React. Line icons come from Lucide (ISC), brand marks from Simple Icons (CC0). Run after changing either list:
//   node scripts/build-motion-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const require = createRequire(import.meta.url);

const LINE = `check x triangle-alert info lightbulb sparkles zap rocket target trophy star heart flame eye eye-off lock key shield user users bot
brain message-square messages-square mail phone calendar clock timer dollar-sign trending-up trending-down chart-bar chart-line chart-pie search
file file-text folder image video camera mic audio-lines music monitor laptop smartphone code terminal database server cloud globe link settings
wrench hammer layers layout-grid list list-checks git-branch workflow play pause repeat refresh-cw download upload share-2 bookmark pen scissors
wand-sparkles puzzle package shopping-cart store briefcase building-2 graduation-cap book-open newspaper megaphone bell gift thumbs-up thumbs-down
arrow-right plug cpu app-window mouse-pointer-click hand coffee moon sun calendar-check hourglass gauge infinity
`.split(/\s+/).filter(Boolean);
const BRANDS = `claude anthropic youtube instagram tiktok x github notion figma google googledrive gmail googlecalendar googlesheets discord stripe
vercel linear googlechrome apple cursor zapier n8n make airtable hubspot shopify wordpress obsidian whatsapp telegram spotify supabase python react
nextdotjs googlegemini perplexity framer webflow loom calendly`.split(/\s+/).filter(Boolean);

const lucideDir = path.join(path.dirname(require.resolve('lucide-react/package.json')), 'dist/esm/icons');
const attrs = (o) => Object.entries(o).filter(([k]) => k !== 'key').map(([k, v]) => `${k}="${String(v).replace(/"/g, '&quot;')}"`).join(' ');
const line = {};
const missing = [];
for (const name of LINE) {
  let source;
  try { source = readFileSync(path.join(lucideDir, `${name}.js`), 'utf8'); } catch { missing.push(name); continue; }
  // The module is `createLucideIcon("Name", [[tag, attrs], ...])`: the node list is plain data.
  const nodes = Function(`return ${source.match(/createLucideIcon\("[^"]+",\s*(\[[\s\S]*?\])\);/)[1]}`)();
  line[name] = nodes.map(([tag, a]) => `<${tag} ${attrs(a)}/>`).join('');
}
const si = require('simple-icons');
const brands = {};
for (const name of BRANDS) {
  const icon = si[`si${name[0].toUpperCase()}${name.slice(1)}`];
  if (!icon) { missing.push(name); continue; }
  brands[name] = { title: icon.title, hex: `#${icon.hex.toLowerCase()}`, path: icon.path };
}
if (missing.length) throw new Error(`Not found: ${missing.join(', ')}`);

const lucideVersion = require('lucide-react/package.json').version, siVersion = JSON.parse(readFileSync(path.join(root, 'node_modules/simple-icons/package.json'), 'utf8')).version;
writeFileSync(path.join(root, 'shared/motion/icons.ts'), `// Generated by scripts/build-motion-icons.mjs from lucide-react ${lucideVersion} (ISC) and simple-icons ${siVersion} (CC0). Do not edit by hand.

/** Line icons: the inner elements of a 24×24 Lucide icon, drawn with the current colour's stroke. */
export const LINE_ICONS: Readonly<Record<string, string>> = ${JSON.stringify(line, null, 1)};

/** Brand marks: one 24×24 path in the brand's colour. */
export const BRAND_ICONS: Readonly<Record<string, { title: string; hex: string; path: string }>> = ${JSON.stringify(brands, null, 1)};
`);
console.log(`${Object.keys(line).length} line icons, ${Object.keys(brands).length} brands`);
